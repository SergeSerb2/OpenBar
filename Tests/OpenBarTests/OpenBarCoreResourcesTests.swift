import Foundation
import Testing
@testable import OpenBarCore

struct OpenBarCoreResourcesTests {
    @Test
    func `resolver finds bundled plugin resources outside an app context`() throws {
        let bundle = try #require(OpenBarCoreResources.bundle)
        #expect(bundle.url(forResource: "provider-plugin-prelude", withExtension: "js") != nil)
    }

    @Test(arguments: ["MacOS", "Helpers"])
    func `resolver prefers the packaged Contents Resources bundle inside an app context`(directory: String) throws {
        // Build a fake .app that mirrors the packaged layout: the resource
        // bundle lives in Contents/Resources, NOT at the app root — the exact
        // shape that made the autogenerated accessor trap at launch (#2738).
        let root = FileManager.default.temporaryDirectory
            .appendingPathComponent("OpenBarCoreResourcesTests-\(UUID().uuidString)")
        let appURL = root.appendingPathComponent("Fake.app")
        let resourcesURL = appURL.appendingPathComponent("Contents/Resources")
        try FileManager.default.createDirectory(at: resourcesURL, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: root) }

        let target = resourcesURL.appendingPathComponent("OpenBar_OpenBarCore.bundle")
        // `Bundle.module` here is the *test* module's bundle; source the copy from
        // OpenBarCore's own resolved bundle (non-app context, proven by the test above).
        let sourceBundle = try #require(OpenBarCoreResources.bundle)
        try FileManager.default.copyItem(at: sourceBundle.bundleURL.resolvingSymlinksInPath(), to: target)

        let fakeApp = try #require(Bundle(url: appURL))
        let executable = appURL.appendingPathComponent("Contents/\(directory)/Tool")
        try FileManager.default.createDirectory(
            at: executable.deletingLastPathComponent(),
            withIntermediateDirectories: true)
        try Data().write(to: executable)
        let resolved = try #require(OpenBarCoreResources.resolve(mainBundle: fakeApp, executableURL: executable))
        #expect(resolved.bundleURL.path.contains("Contents/Resources/OpenBar_OpenBarCore.bundle"))
        #expect(resolved.url(forResource: "provider-plugin-prelude", withExtension: "js") != nil)
    }

    @Test(arguments: ["bundle", "resources"])
    func `resolver finds an executable adjacent resource bundle`(pathExtension: String) throws {
        let root = FileManager.default.temporaryDirectory
            .appendingPathComponent("OpenBarCoreResourcesCLITests-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: root) }

        let sourceBundle = try #require(OpenBarCoreResources.bundle)
        let target = root.appendingPathComponent("OpenBar_OpenBarCore.\(pathExtension)")
        try FileManager.default.copyItem(at: sourceBundle.bundleURL.resolvingSymlinksInPath(), to: target)
        let executableURL = root.appendingPathComponent("OpenBarCLI")
        try Data().write(to: executableURL)

        let resolved = try #require(OpenBarCoreResources.resolve(
            mainBundle: .main,
            executableURL: executableURL,
            swiftPMBuildDirectory: nil))
        #expect(resolved.bundleURL.resolvingSymlinksInPath() == target.resolvingSymlinksInPath())
    }

    @Test
    func `resolver returns nil when executable and build bundles are missing`() throws {
        let root = FileManager.default.temporaryDirectory
            .appendingPathComponent("OpenBarCoreResourcesMissingTests-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: root) }

        #expect(OpenBarCoreResources.resolve(
            mainBundle: .main,
            executableURL: root.appendingPathComponent("OpenBarCLI"),
            swiftPMBuildDirectory: nil) == nil)
    }

    @Test
    func `resource smoke probe reports no failures in a dev context`() {
        // The same probe the packaging launch smoke check runs inside the
        // packaged app (OPENBAR_RESOURCE_SMOKE=1, #2738).
        #expect(OpenBarCoreResourceSmoke.failures().isEmpty)
    }

    @Test
    func `no raw Bundle module accessor usage in OpenBarCore sources`() throws {
        // The autogenerated accessor fatals when the packaged app lacks a
        // root-level copy of the bundle; all resource loads must go through
        // OpenBarCoreResources. Guard against regressions at the source level.
        let sourcesRoot = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent() // OpenBarTests
            .deletingLastPathComponent() // Tests
            .deletingLastPathComponent() // repo root
            .appendingPathComponent("Sources/OpenBarCore")
        let enumerator = try #require(FileManager.default.enumerator(
            at: sourcesRoot,
            includingPropertiesForKeys: nil))
        var offenders: [String] = []
        for case let url as URL in enumerator where url.pathExtension == "swift" {
            guard url.lastPathComponent != "OpenBarCoreResources.swift" else { continue }
            let text = try String(contentsOf: url, encoding: .utf8)
            for (index, line) in text.split(separator: "\n", omittingEmptySubsequences: false).enumerated()
                where line.contains("Bundle.module") && !line.trimmingCharacters(in: .whitespaces).hasPrefix("//")
            {
                offenders.append("\(url.lastPathComponent):\(index + 1)")
            }
        }
        #expect(offenders.isEmpty, "raw Bundle.module usage in OpenBarCore: \(offenders)")
    }
}
